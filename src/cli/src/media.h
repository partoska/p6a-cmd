/**
 * Fetches and prints media items for a given event.
 *
 * @param client   Logged-in client.
 * @param event    UUID of the event to list media for.
 * @param owner    When true, restricts output to media owned by the user.
 * @param favorite When true, restricts output to favorited media.
 * @param fmt      Output format.
 * @return PK_OK on success, or a PK_E* error code on failure.
 */
PKInt pkcMediaList (PKClient *client, const PKChar *event, PKBool owner,
                    PKBool favorite, PKCArgFmt fmt);

