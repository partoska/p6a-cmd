PKCIni *
pkcIniInit (void)
{
  return bkInit (BK_FICASE);
}

PKVoid
pkcIniDestroy (PKCIni *ini)
{
  bkDestroy (ini);
}

PKInt
pkcIniLoad (PKCIni *ini, const PKChar *filename)
{
  if (!ini || !filename)
    {
      return PK_EARG;
    }

  PKCFile *file = pkcFileOpen (filename, PK_FALSE);
  if (!file)
    {
      return PK_EFS;
    }

  BKStatus status = bkRead (ini, pkcIniRead, file);
  pkcFileClose (file);
  if (status != BK_OK && status != BK_EMEM)
    {
      PKC_ERROR ("%s: %s", filename, bkError (ini)->message);
    }

  return pkcIniStatus (status);
}

PKInt
pkcIniSave (const PKCIni *ini, const PKChar *filename)
{
  // The writer cannot continue a value on the next line.
  for (PKSize i = 0; i < bkSectionCount (ini); ++i)
    {
      const BKSection *section = bkSectionAt (ini, i);
      for (PKSize j = 0; j < bkKeyCount (section); ++j)
        {
          if (pkcStrFindAny (bkValueAt (section, j), "\r\n"))
            {
              return PK_EARG;
            }
        }
    }

  PKCFile *file = pkcFileOpen (filename, PK_TRUE);
  if (!file)
    {
      return PK_EFS;
    }

  pkcIniWrite (file, "; Partoska.com Configuration File\n");
  pkcIniWrite (file,
               "; Auto-generated by p6a utility v" PK_VERSION_STRING ".\n");
  pkcIniWrite (
      file, "; Do not modify. More info at <https://www.partoska.com/p6a>\n");

  for (PKSize i = 0; i < bkSectionCount (ini); ++i)
    {
      const BKSection *section = bkSectionAt (ini, i);
      pkcIniWrite (file, "\n[");
      pkcIniWrite (file, bkSectionName (section));
      pkcIniWrite (file, "]\n");
      for (PKSize j = 0; j < bkKeyCount (section); ++j)
        {
          pkcIniWrite (file, bkKeyAt (section, j));
          pkcIniWrite (file, "=");
          pkcIniWrite (file, bkValueAt (section, j));
          pkcIniWrite (file, "\n");
        }
    }

  PKBool failed = pkcFileFailed (file);
  failed = !pkcFileClose (file) || failed;

  return failed ? PK_EFS : PK_OK;
}

const PKChar *
pkcIniGet (const PKCIni *ini, const PKChar *section, const PKChar *key)
{
  return bkGet (ini, section, key);
}

PKInt
pkcIniSet (PKCIni *ini, const PKChar *section, const PKChar *key,
           const PKChar *value)
{
  if (!value || pkcStrFindAny (value, "\r\n"))
    {
      return PK_EARG;
    }

  return pkcIniStatus (bkSet (ini, section, key, value));
}

PKBool
pkcIniHasValue (const PKCIni *ini, const PKChar *key, const PKChar *value)
{
  for (PKSize i = 0; i < bkSectionCount (ini); ++i)
    {
      const PKChar *found = bkSectionGet (bkSectionAt (ini, i), key);
      if (found && pkcStrEq (found, value))
        {
          return PK_TRUE;
        }
    }

  return PK_FALSE;
}
